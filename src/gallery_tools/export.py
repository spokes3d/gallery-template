"""Write the public gallery: the public studies of a private gallery, as a repository.

The public repository is generated, never edited by hand. ``export`` empties the target folder
(keeping ``.git``, and ``.venv`` and ``node_modules`` of a local checkout) and writes:

- ``studies/<stem>/`` of every study with ``public: true``, without the files its ``exclude``
  globs name and without smoke results;
- ``gallery.yml``, the site of the public gallery (``public:`` of the private one);
- ``pyproject.toml``, with the codes the public studies use and their ``[tool.uv.sources]``
  from the private gallery, and the gallery tools;
- ``docs/``, the site: the npm files of the private gallery, an Astro config and a home page
  (unless the overlay brings its own), and the overlay;
- the workflows, a smoke test and a README;
- ``.gallery-export.json``: the source repository and commit, and the studies.

The overlay is a folder of the private gallery (``public/`` by default) copied verbatim into the
public repository last: the home page and any other page the public site should have.

A study goes public only if ``check_public`` finds nothing: a ``result`` needs its preprint,
private codes are not allowed and the script must not import helper modules of the repository.
"""

from __future__ import annotations

import fnmatch
import json
import shutil
import subprocess
import tomllib
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

from gallery_tools.config import Gallery, GalleryError
from gallery_tools.study import (
    Study,
    discover,
    distribution_name,
    local_modules,
)

DOCS_FILES = (
    "package.json",
    "package-lock.json",
    "tsconfig.json",
    ".gitignore",
    "src/content.config.ts",
)
SKELETON = {
    "github/workflows/docs.yml": ".github/workflows/docs.yml",
    "github/workflows/tests.yml": ".github/workflows/tests.yml",
    "github/workflows/sync_pr.yml": ".github/workflows/sync_pr.yml",
    "gitignore": ".gitignore",
    "tests/test_studies.py": "tests/test_studies.py",
}
#: Import names whose distribution is not the import name with dashes.
DISTRIBUTIONS = {"yaml": "pyyaml", "PIL": "pillow", "sklearn": "scikit-learn"}


def public_studies(gallery: Gallery) -> list[Study]:
    """The studies marked ``public: true``."""
    return [s for s in discover(gallery) if s.public]


def check_public(gallery: Gallery) -> dict[str, list[str]]:
    """The problems of each public study that keep it from going public."""
    local = local_modules(gallery)
    out = {}
    for study in public_studies(gallery):
        problems = study.problems(gallery) + study.public_problems(gallery, local)
        if problems:
            out[study.stem] = problems
    return out


def _excluded(study: Study, path: Path) -> bool:
    """Whether a file of the study stays private."""
    rel = path.relative_to(study.folder).as_posix()
    if "__pycache__" in rel.split("/") or rel.startswith("results/smoke."):
        return True
    return any(
        fnmatch.fnmatch(rel, pattern) or rel.startswith(pattern.rstrip("/") + "/")
        for pattern in study.meta.get("exclude") or []
    )


def _requirements(gallery: Gallery, studies: list[Study]) -> list[str]:
    """The distributions the public studies need."""
    names = {c for s in studies for c in s.codes}
    for study in studies:
        names |= {
            DISTRIBUTIONS.get(m, distribution_name(m)) for m in study.third_party()
        }
    return sorted(names, key=str.lower)


def _source_commit(root: Path) -> str:
    """The commit of the private gallery."""
    try:
        return subprocess.run(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _toml_string(value: str) -> str:
    """A TOML basic string."""
    return json.dumps(value)


def _toml_inline(table: dict[str, Any]) -> str:
    """A TOML inline table of strings."""
    return (
        "{ "
        + ", ".join(f"{k} = {_toml_string(str(v))}" for k, v in table.items())
        + " }"
    )


def pyproject(gallery: Gallery, studies: list[Study]) -> str:
    """The ``pyproject.toml`` of the public gallery."""
    public = gallery.public
    assert public is not None
    source_file = gallery.root / "pyproject.toml"
    source = tomllib.loads(source_file.read_text()) if source_file.exists() else {}
    project = source.get("project", {})
    requires = _requirements(gallery, studies)
    sources = source.get("tool", {}).get("uv", {}).get("sources", {})
    lines = [
        "# Generated by `gallery export` from the private gallery: do not edit by hand.",
        "[build-system]",
        'build-backend = "setuptools.build_meta"',
        'requires = [ "setuptools" ]',
        "",
        "[project]",
        f"name = {_toml_string(public.repo)}",
        'version = "0.1.0"',
        f"description = {_toml_string(public.description)}",
        'readme = "README.md"',
        f"requires-python = {_toml_string(project.get('requires-python', '>=3.11'))}",
        "dependencies = [",
        f"  {_toml_string(public.tools)},",
        *[f"  {_toml_string(r)}," for r in requires],
        "]",
        'optional-dependencies.docs = [ "ipykernel" ]',
        'optional-dependencies.test = [ "pytest" ]',
        "",
        "[tool.setuptools]",
        "py-modules = [  ]",
        "",
        "[tool.pytest]",
        'ini_options.testpaths = [ "tests" ]',
        'ini_options.addopts = "-ra"',
    ]
    used = {k: v for k, v in sources.items() if k in requires}
    if used:
        lines += ["", "[tool.uv.sources]"]
        lines += [f"{k} = {_toml_inline(v)}" for k, v in sorted(used.items())]
    return "\n".join(lines) + "\n"


def astro_config(gallery: Gallery) -> str:
    """The Astro config of the public site."""
    public = gallery.public
    assert public is not None
    return f"""// @ts-check
// Generated by `gallery export`: the public gallery at https://{public.owner}.github.io/{public.repo}/.
import {{ defineDocs }} from '@max-models/starlight-theme';

export default defineDocs({{
\trepo: {json.dumps(public.repo)},
\towner: {json.dumps(public.owner)},
\ttitle: {json.dumps(public.title)},
\tdescription: {json.dumps(public.description)},
\tnav: [{{ label: 'Studies', link: '/studies/' }}],
\tsidebar: [
\t\t{{ label: 'Studies', items: [{{ autogenerate: {{ directory: 'studies' }} }}] }},
\t],
}});
"""


def home_page(gallery: Gallery) -> str:
    """The home page of the public site, when the overlay has none."""
    public = gallery.public
    assert public is not None
    return f"""---
title: {json.dumps(public.title)}
description: {json.dumps(public.description)}
---

{public.description}

[Browse the studies](/{public.repo}/studies/).
"""


def readme(gallery: Gallery, studies: list[Study]) -> str:
    """The README of the public gallery."""
    public = gallery.public
    assert public is not None
    url = f"https://{public.owner}.github.io/{public.repo}"
    rows = [
        f"| [{s.title}]({url}/studies/{s.slug}/) | {s.kind} | {', '.join(s.codes) or 'none'} |"
        for s in studies
    ]
    return "\n".join(
        [
            f"# {public.title}",
            "",
            public.description,
            "",
            f"Site: <{url}/>",
            "",
            "| Study | Kind | Codes |",
            "|---|---|---|",
            *rows,
            "",
            "## Running a study",
            "",
            "```bash",
            "uv sync",
            "uv run python studies/<study>/study.py --preset smoke",
            "uv run gallery build --cached-only   # the pages of the site, from the cached results",
            "```",
            "",
            "This repository is generated from a private gallery with `gallery export` "
            "([gallery-template](https://github.com/spokes3d/gallery-template)): changes "
            "come in as pull requests from the sync and are not made here by hand.",
            "",
        ]
    )


def _has_page(overlay: Path, link: str) -> bool:
    """Whether the overlay brings the page ``link`` (a path of the site, e.g. ``/programme/``)."""
    page = overlay / "docs" / "src" / "content" / "docs" / link.strip("/")
    return any(
        path.is_file()
        for path in (
            page.with_suffix(".md"),
            page.with_suffix(".mdx"),
            page / "index.md",
            page / "index.mdx",
        )
    )


def public_fields(gallery: Gallery) -> dict[str, dict[str, Any]]:
    """The extra fields of the public gallery: a link stays only if its page goes public too."""
    public = gallery.public
    assert public is not None
    overlay = gallery.root / public.overlay
    fields = {}
    for key, spec in gallery.fields.items():
        spec = dict(spec)
        if spec.get("link") and not _has_page(overlay, spec["link"]):
            spec.pop("link")
            spec.pop("link_text", None)
        fields[key] = spec
    return fields


#: Kept when the target is emptied: git, and the environments of a local checkout.
KEEP = {".git", ".venv", "node_modules"}


def _clean(target: Path) -> None:
    """Empty ``target``, keeping ``.git``, ``.venv`` and ``node_modules`` at any depth."""
    target.mkdir(parents=True, exist_ok=True)
    for path in target.iterdir():
        if path.name in KEEP:
            continue
        if path.is_dir() and not path.is_symlink():
            if any(path.rglob("node_modules")):
                _clean(path)
                if not any(path.iterdir()):
                    path.rmdir()
            else:
                shutil.rmtree(path)
        else:
            path.unlink()


def export(gallery: Gallery, target: Path) -> list[Study]:
    """Write the public gallery into ``target`` (emptied first; ``.git``, ``.venv`` and ``node_modules`` kept).

    Parameters
    ----------
    gallery : Gallery
        The private gallery; its ``gallery.yml`` needs a ``public:`` section.
    target : Path
        The folder of the public repository.

    Returns
    -------
    list of Study
        The studies exported.
    """
    public = gallery.public
    if public is None:
        raise GalleryError("gallery.yml has no `public:` section")
    problems = check_public(gallery)
    if problems:
        text = "\n".join(
            f"  {stem}: {p}" for stem, items in problems.items() for p in items
        )
        raise GalleryError(f"studies marked public cannot go public:\n{text}")
    target = target.resolve()
    if target == gallery.root or gallery.root in target.parents:
        raise GalleryError("the target must be outside the gallery")
    studies = public_studies(gallery)
    _clean(target)

    for study in studies:
        for path in sorted(study.folder.rglob("*")):
            if path.is_file() and not _excluded(study, path):
                dest = target / "studies" / study.stem / path.relative_to(study.folder)
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, dest)

    config = {k: v for k, v in gallery.raw.items() if k not in ("public", "site")}
    config["fields"] = public_fields(gallery)
    config = {
        "site": {
            "title": public.title,
            "description": public.description,
            "owner": public.owner,
            "repo": public.repo,
        },
        **config,
    }
    (target / "gallery.yml").write_text(
        "# Generated by `gallery export` from the private gallery: do not edit by hand.\n"
        + yaml.safe_dump(config, sort_keys=False, allow_unicode=True)
    )
    (target / "pyproject.toml").write_text(pyproject(gallery, studies))
    (target / "README.md").write_text(readme(gallery, studies))

    for name in DOCS_FILES:
        source = gallery.docs / name
        if source.exists():
            dest = target / "docs" / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, dest)
    (target / "docs" / "astro.config.mjs").write_text(astro_config(gallery))
    home = target / "docs" / "src" / "content" / "docs" / "index.mdx"
    home.parent.mkdir(parents=True, exist_ok=True)
    home.write_text(home_page(gallery))

    skeleton = resources.files("gallery_tools") / "skeleton"
    for source_name, dest_name in SKELETON.items():
        dest = target / dest_name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text((skeleton / source_name).read_text())

    overlay = gallery.root / public.overlay
    if overlay.is_dir():
        shutil.copytree(overlay, target, dirs_exist_ok=True)

    stamp = {
        "source": f"{gallery.owner}/{gallery.repo}",
        "commit": _source_commit(gallery.root),
        "studies": [s.stem for s in studies],
    }
    (target / ".gallery-export.json").write_text(json.dumps(stamp, indent=2) + "\n")
    return studies
